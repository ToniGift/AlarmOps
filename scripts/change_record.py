#!/usr/bin/env python3
"""Generate a markdown change record for an alarm-limit change.

The standards table is a REFERENCE MAPPING, not a certification.
"""
import argparse
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

import _common  # noqa: F401
from _common import git_show

from alarmops.rules import RulesError, load_rules, load_rules_text

FIELDS = ("low_low", "low", "high", "high_high", "deadband", "delay_samples")

MAPPING = [
    ("Rationalization / change justification",
     "ANSI/ISA-18.2 and IEC 62682: alarm lifecycle (management of change stage)",
     "Change reason and measured effect recorded below"),
    ("Change authorisation",
     "ANSI/ISA-18.2 and IEC 62682: management of change",
     "Merge request review plus a human approval gate before production"),
    ("Verification of the change",
     "ANSI/ISA-18.2 and IEC 62682: implementation / testing of alarm changes",
     "Replay test measured detection rate and false alarms"),
    ("Audit trail",
     "ANSI/ISA-18.2 and IEC 62682: audit and monitoring stages",
     "This record, pipeline history and the post-deploy monitor"),
    ("Secure change handling",
     "IEC 62443 series: secure development and change management practices",
     "Secret detection and scan results listed below"),
]


def diff_rules(base, head):
    rows = []
    for tag in sorted(set(base) | set(head)):
        b, h = base.get(tag), head.get(tag)
        if b is None or h is None:
            rows.append((tag, "(tag)", "absent" if b is None else "present",
                         "present" if h is None else "absent"))
            continue
        for f in FIELDS:
            if getattr(b, f) != getattr(h, f):
                rows.append((tag, f, getattr(b, f), getattr(h, f)))
    return rows


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--head-rules", default="alarms.yaml")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--base-rules")
    g.add_argument("--base-ref")
    ap.add_argument("--rules-path-in-repo", default="alarms.yaml")
    ap.add_argument("--compare-json", default="out/compare.json")
    ap.add_argument("--scan-status", default="See the pipeline's security reports (Secret Detection etc.)")
    ap.add_argument("--reason", default=os.environ.get("CI_MERGE_REQUEST_TITLE", "(no reason supplied)"))
    ap.add_argument("--out", default="out/change_record.md")
    a = ap.parse_args()

    try:
        head = load_rules(a.head_rules)
        if a.base_rules:
            base = load_rules(a.base_rules)
        else:
            ref = a.base_ref or (f"origin/{os.environ['CI_MERGE_REQUEST_TARGET_BRANCH_NAME']}"
                                 if os.environ.get("CI_MERGE_REQUEST_TARGET_BRANCH_NAME") else "main")
            base = load_rules_text(git_show(ref, a.rules_path_in_repo))
        cmp_ = json.loads(Path(a.compare_json).read_text())
    except (RulesError, FileNotFoundError, json.JSONDecodeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    b, h, res = cmp_["base"], cmp_["head"], cmp_["result"]
    env = os.environ
    L = [
        "# Alarm Limit Change Record",
        "",
        "> SIMULATION. Generated by AlarmOps. The standards mapping is a reference "
        "mapping, **not a certification** or a compliance claim.",
        "",
        "## Context",
        f"- Generated (UTC): {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S')}",
        f"- Reason / title: {a.reason}",
        f"- Commit: {env.get('CI_COMMIT_SHA', '(local run)')}",
        f"- Merge request: {env.get('CI_MERGE_REQUEST_IID', '(none)')}",
        f"- Pipeline: {env.get('CI_PIPELINE_URL', '(local run)')}",
        "",
        "## What changed",
    ]
    rows = diff_rules(base, head)
    if rows:
        L += ["", "| Tag | Setting | Before | After |", "|---|---|---|---|"]
        L += [f"| {t} | {f} | {o} | {n} |" for t, f, o, n in rows]
    else:
        L.append("\nNo alarm settings changed.")
    L += [
        "",
        "## Measured effect (replay of simulated labelled faults)",
        "",
        "| Metric | Before | After |",
        "|---|---|---|",
        f"| Fault detection rate | {b['detection_rate']:.1%} ({b['faults_detected']}/{b['faults_total']}) "
        f"| {h['detection_rate']:.1%} ({h['faults_detected']}/{h['faults_total']}) |",
        f"| False alarms | {b['false_alarm_count']} | {h['false_alarm_count']} |",
        f"| Gate result | | {'PASS' if res['passed'] else 'FAIL'} |",
    ]
    if res["violations"]:
        L += ["", "Gate violations:"] + [f"- {v}" for v in res["violations"]]
    if res["newly_missed"]:
        L += ["", "Faults no longer detected: " + ", ".join(f["fault_id"] for f in res["newly_missed"])]
    L += [
        "",
        "## Security scan status",
        f"- {a.scan_status}",
        "",
        "## Approval",
        "- Production deployment requires a manual human approval in the pipeline (Supervised autonomy).",
        "- Approver: ______________________   Date: ______________",
        "",
        "## Reference mapping (not a certification)",
        "",
        "| Change-control element | Reference area | AlarmOps evidence |",
        "|---|---|---|",
    ]
    L += [f"| {x} | {y} | {z} |" for x, y, z in MAPPING]
    L += ["", "_Clause-level references are intentionally omitted; verify against the "
              "current published standards before relying on this record._", ""]
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
